import assert from "node:assert/strict";
import test from "node:test";
import { randomBytes, randomUUID } from "node:crypto";
import express from "express";
import multer from "multer";
import { registerNormalCompanyManagementRoutes, normalManagementView, resolveNormalManagementContext } from "./normal_company_management.js";
import { renderConnectPage, renderSuccessPage } from "./connection_page.js";
import { getConnectionStore, claimConnectionCodeForSession } from "./connection_store.js";
import { createConnectionSuccessPage, getConnectionSuccessPage } from "./connection_success_session.js";
import { seedClaimableConnection } from "./connection_test_helpers.js";
import { decodeStoredApiKey } from "./credential_secret.js";
import { setCompanyCredentialValidator, resetCompanyCredentialValidator } from "./credential_validation.js";
